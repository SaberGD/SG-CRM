const a = require(process.env.HOME + '/work/new-accounting-sys/functions/node_modules/firebase-admin');
const crm = a.initializeApp({ projectId: 'sg-crm-e3a38' }, 'crm'); const db = a.firestore(crm);
(async () => {
  const snap = await db.collection('integrationEvents').select('sourceSystem').get();
  const junk = snap.docs.filter((d) => /^accounting_booking_.+_\d{13}$/.test(d.id));
  console.log('integrationEvents total:', snap.size, '| generated by the resync loop (id ends with a timestamp):', junk.length, '| other:', snap.size - junk.length);
  if (process.argv.includes('--apply')) {
    for (let i = 0; i < junk.length; i += 400) { const b = db.batch(); junk.slice(i, i + 400).forEach((d) => b.delete(d.ref)); await b.commit(); }
    console.log('deleted', junk.length);
  }
})();
